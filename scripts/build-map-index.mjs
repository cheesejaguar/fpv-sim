#!/usr/bin/env node
// Regenerates public/maps/community/index.json from the community map packages
// (public/maps/community/<id>/map.json), so a new map needs no code changes: the app registers
// every map listed in the index. Runs before `npm run dev` / `npm run build`.
//   node scripts/build-map-index.mjs           write the index
//   node scripts/build-map-index.mjs --check   exit 1 if the committed index is stale (CI)
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const COMMUNITY_DIR = fileURLToPath(new URL('../public/maps/community/', import.meta.url));

/** Build the index object for a community directory (pure: no writes). */
export function buildIndex(dir = COMMUNITY_DIR) {
  const maps = [], problems = [];
  for (const id of readdirSync(dir).sort()) {
    const folder = join(dir, id);
    if (!statSync(folder).isDirectory()) continue;
    const file = join(folder, 'map.json');
    if (!existsSync(file)) { problems.push(`${id}/: no map.json`); continue; }
    let doc;
    try { doc = JSON.parse(readFileSync(file, 'utf8')); } catch (e) { problems.push(`${id}/map.json: ${e.message}`); continue; }
    const m = doc?.meta ?? {};
    if (m.id !== id) { problems.push(`${id}/map.json: meta.id "${m.id}" must equal the folder name`); continue; }
    maps.push({
      id, name: String(m.name ?? id), author: String(m.author ?? ''), license: String(m.license ?? ''), version: String(m.version ?? ''),
      ...(m.description && { description: String(m.description) }),
      ...(m.preview && { preview: `maps/community/${id}/${m.preview}` }),
      ...(Array.isArray(m.tags) && m.tags.length && { tags: m.tags.map(String) }),
    });
  }
  return { index: { $comment: 'Generated by scripts/build-map-index.mjs from public/maps/community/*/map.json. Do not edit.', format: 'fpvsim-map-index', formatVersion: 1, maps }, problems };
}

export const serialize = (index) => JSON.stringify(index, null, 2) + '\n';

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { index, problems } = buildIndex();
  for (const p of problems) console.error(`map index: skipped ${p}`);
  const out = join(COMMUNITY_DIR, 'index.json'), text = serialize(index);
  if (process.argv.includes('--check')) {
    const cur = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== text) { console.error('public/maps/community/index.json is out of date: run `npm run map:index` and commit it'); process.exit(1); }
    console.log(`map index up to date (${index.maps.length} community maps)`);
  } else {
    writeFileSync(out, text);
    console.log(`map index: ${index.maps.length} community maps -> public/maps/community/index.json`);
  }
  if (problems.length) process.exit(1);
}
