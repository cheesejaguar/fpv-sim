#!/usr/bin/env node
// Regenerates server/src/trackGates.ts: the gates of every leaderboard track (TRACKS in
// server/src/leaderboardCore.ts), taken from the built-in maps, so the relay can check that a
// posted replay passes each gate in order at its split time (server/src/replayCheck.ts).
// tests/leaderboard.test.ts fails when the table no longer matches the maps.
//   node scripts/build-track-gates.mjs           write the table
//   node scripts/build-track-gates.mjs --check   exit 1 if the committed table is stale
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadTs } from './lib/load-ts.mjs';

const OUT = fileURLToPath(new URL('../server/src/trackGates.ts', import.meta.url));
const COMMUNITY = fileURLToPath(new URL('../public/maps/community/', import.meta.url));

function dirSource(base) {
  const files = [];
  const walk = (d) => { for (const n of readdirSync(d)) { const p = join(d, n); if (statSync(p).isDirectory()) walk(p); else files.push({ path: relative(base, p).split(sep).join('/'), size: statSync(p).size }); } };
  walk(base);
  return { list: async () => files, url: (p) => `file://${p}`, read: async (p) => new Uint8Array(readFileSync(join(base, p))) };
}

const r3 = (x) => Math.round(x * 1000) / 1000;
const r5 = (x) => Math.round(x * 1e5) / 1e5;
/** What the pass test needs of a gate (ENU m / rad), rounded to 1 mm and 10 µrad. */
const geom = (g) => ({ id: g.id, kind: g.kind, x: r3(g.c.x), y: r3(g.c.y), z: r3(g.c.z), yaw: r5(g.yaw), w: r3(g.width), h: r3(g.height) });

const { mods: [maps, fmt, core], close } = await loadTs('src/maps/maps.ts', 'src/maps/mapFormat.ts', 'server/src/leaderboardCore.ts');
try {
  const table = {};
  for (const key of Object.keys(core.TRACKS)) {
    const [id, course = ''] = key.split(':');
    const e = maps.MAP_LIST[id];
    if (!e) throw new Error(`${key}: no such map in this build`);
    const m = e.community ? (await fmt.loadMapPackage(dirSource(join(COMMUNITY, id)))).build(id) : maps.MAPS[id]();
    const gates = course ? m.courses?.find((c) => c.id === course)?.gates : m.gates;
    if (!gates?.length) throw new Error(`${key}: no gates`);
    table[key] = gates.map(geom);
  }
  const key = (k) => (/^[a-z_]\w*$/i.test(k) ? k : `'${k}'`);
  const obj = (g) => `{ ${Object.entries(g).map(([k, v]) => `${k}: ${typeof v === 'string' ? `'${v}'` : v}`).join(', ')} }`;
  const body = Object.entries(table).map(([k, gs]) => `  ${key(k)}: [\n${gs.map((g) => `    ${obj(g)},`).join('\n')}\n  ],`).join('\n');
  const text = `// Generated by scripts/build-track-gates.mjs from the built-in maps. Do not edit: run
//   node scripts/build-track-gates.mjs
// after changing a leaderboard track's gates (tests/leaderboard.test.ts checks it against the maps).
// Each track's gates in lap order, as the pass test needs them: c = (x, y, z), the bottom centre of
// the counted opening (dive: frame centre; flag: pole foot), yaw = direction of travel (CCW from +y),
// w × h = clear opening (ENU metres, radians).

export type GateKind = 'square' | 'arch' | 'flag' | 'dive' | 'hurdle' | 'ladder';
export interface TrackGate { id: number; kind: GateKind; x: number; y: number; z: number; yaw: number; w: number; h: number }

export const TRACK_GATES: Readonly<Record<string, readonly TrackGate[]>> = Object.freeze({
${body}
});
`;
  if (process.argv.includes('--check')) {
    const cur = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
    if (cur !== text) { console.error('server/src/trackGates.ts is out of date: run `node scripts/build-track-gates.mjs` and commit it'); process.exitCode = 1; }
    else console.log(`track gates up to date (${Object.keys(table).length} tracks)`);
  } else {
    writeFileSync(OUT, text);
    console.log(`track gates: ${Object.keys(table).length} tracks -> server/src/trackGates.ts`);
  }
} finally { await close(); }
